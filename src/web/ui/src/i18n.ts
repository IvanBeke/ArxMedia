export function useI18n() {
  const prefs = usePreferencesStore()
  const locale = computed(() => prefs.locale)
  const t = (key: MessageKey, params: MessageParams = {}): string => {
    const localeMessages = locale.value === 'es' ? messages.es : messages.en
    const template = localeMessages[key] ?? messages.en[key]
    return template.replace(/\{(\w+)\}/g, (_match: string, token: string) => {
      const value = params[token]
      return value === undefined || value === null ? '' : String(value)
    })
  }
  return { t, locale }
}

export function formatDateByLocale(value: unknown): string {
  if (!value) return ''
  const prefs = usePreferencesStore()
  const locale = prefs.locale === 'es' ? 'es-ES' : 'en-US'
  return formatTemporalDate(value, locale, { month: 'long', day: 'numeric', year: 'numeric' })
}

export function formatDateTimeByLocale(
  value: unknown,
  options: Intl.DateTimeFormatOptions = {},
): string {
  if (!value) return ''
  const prefs = usePreferencesStore()
  const locale = prefs.locale === 'es' ? 'es-ES' : 'en-US'
  return formatTemporalDateTime(value, locale, {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    ...options,
    hour12: false,
  })
}
